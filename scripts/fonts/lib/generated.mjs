import { familyCacheRelativePath } from './paths.mjs';

function variantFeatureSettings(variant) {
  return variant.features?.join(', ');
}

function variantVariationSettings(variant) {
  if (!variant.variationSettings) return undefined;
  return Object.entries(variant.variationSettings)
    .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
    .map(([axis, value]) => `"${axis}" ${value}`)
    .join(', ');
}

function sortIds(families) {
  return Object.keys(families).sort();
}

function overrideByFile(config) {
  return new Map(
    (config?.families ?? []).flatMap((family) =>
      (family.variantOverrides ?? []).map((variant) => [`${family.id}:${variant.file}`, variant]),
    ),
  );
}

export function buildLocalFontDefinitions(snapshot, config) {
  const overrides = overrideByFile(config);
  return sortIds(snapshot.families).map((id) => {
    const family = snapshot.families[id];
    const cacheDirectory = familyCacheRelativePath(snapshot.catalogVersion, id, family.version);
    return {
      name: family.manifest.familyName,
      cssVariable: family.manifest.cssVariable,
      // Astro's variable must expose only the primary face. Design CSS owns
      // the complete, ordered fallback chain where it controls CJK ordering.
      fallbacks: [],
      variants: family.manifest.variants.map((variant) => {
        const fileName = variant.file.slice('fonts/'.length);
        const override = overrides.get(`${id}:${fileName}`);
        const registration = { ...variant, ...override };
        return {
          src: [`./${cacheDirectory}/${variant.file}`],
          weight: registration.weight,
          style: registration.style,
          ...(registration.stretch ? { stretch: registration.stretch } : {}),
          display: registration.display,
          ...(registration.unicodeRange ? { unicodeRange: registration.unicodeRange } : {}),
          ...(variantFeatureSettings(registration)
            ? { featureSettings: variantFeatureSettings(registration) }
            : {}),
          ...(variantVariationSettings(registration)
            ? { variationSettings: variantVariationSettings(registration) }
            : {}),
        };
      }),
    };
  });
}

export function renderGeneratedSource(snapshot, config) {
  const definitions = buildLocalFontDefinitions(snapshot, config);
  return [
    '/**',
    ' * Generated by `npm run fonts:update` from fonts.catalog.json.',
    ' * Do not edit manually.',
    ' */',
    'type LocalFontVariant = {',
    '  src: [string, ...string[]];',
    '  weight: string;',
    "  style: 'normal' | 'italic' | 'oblique';",
    '  stretch?: string;',
    "  display: 'auto' | 'block' | 'swap' | 'fallback' | 'optional';",
    '  unicodeRange?: [string, ...string[]];',
    '  featureSettings?: string;',
    '  variationSettings?: string;',
    '};',
    '',
    'type LocalFontDefinition = {',
    '  name: string;',
    '  cssVariable: string;',
    '  fallbacks: string[];',
    '  variants: LocalFontVariant[];',
    '};',
    '',
    `export const LOCAL_FONT_CATALOG_VERSION = ${JSON.stringify(snapshot.catalogVersion)};`,
    '',
    `export const localFontDefinitions: LocalFontDefinition[] = ${JSON.stringify(definitions, null, 2)};`,
    '',
  ].join('\n');
}

export function registrationFamilySummary(snapshot) {
  return sortIds(snapshot.families).map((id) => {
    const family = snapshot.families[id];
    return {
      id,
      name: family.manifest.familyName,
      cssVariable: family.manifest.cssVariable,
      role: family.manifest.role,
      variants: family.manifest.variants.length,
    };
  });
}
